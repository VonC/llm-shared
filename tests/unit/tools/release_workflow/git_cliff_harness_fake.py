type Answer = bytes | Callable[[GitCall], bytes]


def asset_name(version: str) -> str:
    """Name the Windows asset of a version."""
    return f"git-cliff-{version}-{PLATFORM_TRIPLE}.zip"


def release_metadata(version: str, *, digest: bool = True, size: int | None = None, tag: str | None = None) -> str:
    """Write GitHub's release metadata for a synthetic archive: its asset, size and `sha256:` digest or null."""
    archive = synthetic_archive(version)
    asset = {
        "name": asset_name(version), "size": len(archive) if size is None else size,
        "digest": f"sha256:{hashlib.sha256(archive).hexdigest()}" if digest else None,
        "browser_download_url": f"https://github.com/orhun/git-cliff/releases/download/v{version}/{asset_name(version)}",
    }
    other = {"name": f"git-cliff-{version}-x86_64-unknown-linux-gnu.tar.gz", "size": 1, "digest": None}
    return json.dumps({"tag_name": f"v{version}" if tag is None else tag, "assets": [other, asset]})


def metadata(version: str, *, digest: bool = True, size: int | None = None) -> Child:
    """The metadata worker child reporting a version's release metadata."""
    return Child(stdout=outcome_line("ok", metadata=release_metadata(version, digest=digest, size=size)))


@dataclass
class GitCall:
    """One recorded Git call: arguments after the executable, subcommand, cwd, environment, input and stdin setting."""

    arguments: list[str]
    command: str
    cwd: Path
    environment: dict[str, str]
    input: bytes | None
    stdin: object

    @property
    def action(self) -> str:
        """Name the subcommand with its first argument, such as `worktree remove`."""
        index = self.arguments.index(self.command) if self.command in self.arguments else len(self.arguments)
        return " ".join([self.command, *self.arguments[index + 1:index + 2]])


def _command(arguments: Sequence[str]) -> str:
    """Find the subcommand after the global options and the `-c` pairs."""
    position = 0
    while position < len(arguments) and (arguments[position] in _GLOBAL_OPTIONS or arguments[position] == "-c"):
        position += 2 if arguments[position] == "-c" else 1
    return arguments[position] if position < len(arguments) else ""


@dataclass
class FakeGit:
    """A recording `subprocess.run` for Git: `--version` answered, every other call recorded and answered by subcommand."""

    answers: dict[str, Answer] = field(default_factory=dict[str, Answer])
    calls: list[GitCall] = field(default_factory=list[GitCall])
    failures: dict[str, tuple[int, bytes]] = field(default_factory=dict[str, tuple[int, bytes]])

    def __call__(self, args: Sequence[str], **kwargs: object) -> subprocess.CompletedProcess[bytes]:
        """Record one call and play its answer."""
        arguments = [str(argument) for argument in args[1:]]
        if arguments == ["--version"]:
            return subprocess.CompletedProcess(args, 0, GIT_VERSION, b"")
        environment = cast("dict[str, str]", kwargs["env"])
        given = kwargs.get("input")
        call = GitCall(arguments, _command(arguments), Path(str(kwargs["cwd"])), dict(environment),
                       given if isinstance(given, bytes) else None, kwargs.get("stdin", "absent"))
        self.calls.append(call)
        answer = self.answers.get(call.command, b"")
        stdout = answer if isinstance(answer, bytes) else answer(call)
        status, stderr = self.failures.get(call.action, (0, b""))
        return subprocess.CompletedProcess(args, status, stdout, stderr)

    def of(self, command: str) -> list[GitCall]:
        """Return the recorded calls of one subcommand, in order."""
        return [call for call in self.calls if call.command == command]


def git_context(tmp_path: Path, monkeypatch: pytest.MonkeyPatch, fake: FakeGit, source: Mapping[str, str] | None = None) -> GitExecutionContext:
    """Select a fake `git.exe` in a PATH directory and build a real context over the recording `subprocess.run`."""
    installed = tmp_path / "installed"
    installed.mkdir(exist_ok=True)
    (installed / "git.exe").touch()
    monkeypatch.setattr(subprocess, "run", fake)
    return GitExecutionContext.create({"PATH": str(installed), **({} if source is None else source)}, original_cwd=tmp_path,
                                      non_interactive=True)


def tag_listing(tags: Sequence[tuple[str, str]]) -> bytes:
    """Write the six-field tag records of `GitExecutionContext.tag_records` for annotated tags on given commits."""
    records = "".join(
        f"{name}\0tag\0{hashlib.sha1(name.encode(), usedforsecurity=False).hexdigest()}\0commit\0{commit}\0Release {name}\n\0\n"
        for name, commit in tags
    )
    return records.encode()


def refs_listing(hashes: FixtureHashes) -> bytes:
    """Write `refname NUL objectname` lines for the fixture head and its tags."""
    lines = [f"refs/heads/main\0{hashes.head}", *(f"refs/tags/{name}\0{sha}" for name, sha in hashes.tags)]
    return "".join(f"{line}\n" for line in lines).encode()


def _case_key(request: ChildRequest) -> str:
    """Name the case of a git-cliff run: its repository, by working directory, and its range after `--`."""
    repository = "fixture" if request.cwd is not None and request.cwd.name == "fixture" else "llm-shared"
    after = request.arguments[request.arguments.index("--") + 1:]
    return f"{repository} {after[0] if after else 'full history'}"


@dataclass
class CliffRuns:
    """The launch seam of git-cliff runs: each request recorded, answered by version and case, identical by default."""

    outputs: dict[tuple[str, str], tuple[int, bytes]] = field(default_factory=dict[tuple[str, str], tuple[int, bytes]])
    requests: list[ChildRequest] = field(default_factory=list[ChildRequest])
    hang: set[str] = field(default_factory=set[str])

    def __call__(self, request: ChildRequest) -> ChildOutcome:
        """Answer one run of the version named by its executable's directory."""
        self.requests.append(request)
        version = request.executable.parent.name
        if version in self.hang:
            return ChildOutcome(status=1, stdout=b"", stderr=b"", timed_out=True, identity=RUN)
        status, stdout = self.outputs.get((version, _case_key(request)), (0, SAME_OUTPUT))
        return ChildOutcome(status=status, stdout=stdout, stderr=b"", timed_out=False, identity=RUN)

    def invocations(self, *versions: str) -> dict[str, Callable[[], GitCliffInvocation]]:
        """Give each version a provider of fresh invocation objects over this seam."""
        def provider(version: str) -> Callable[[], GitCliffInvocation]:
            executable = Path(f"C:/evidence/{version}/git-cliff.exe")
            return lambda: GitCliffInvocation(executable, version, FakeGuard(executable, 900), launch=self)
        return {version: provider(version) for version in versions}


_ACQUIRED = "2026-11-20T18:00:00+01:00"
SAMPLE_RANGES = (*chained_ranges("llm-shared", ("v0.1.0",)), *chained_ranges("fixture", TAGS))
DIFFERING = RangeCase("fixture", "v0.1.0..v0.2.0-SNAPSHOT")
DIFFERING_INDEX = SAMPLE_RANGES.index(DIFFERING)
_HUNK = "@@ -1,2 +1,2 @@\n ## [v0.2.0-SNAPSHOT]\n-### Bug fixes\n+### Security"


@cache
def sample_candidate(version: str) -> Candidate:
    """The trust record identity of a version's synthetic archive: upstream digest for the pin, evidence only for the baseline.

    Cached: the archive is deterministic and the frozen identity is shared by every sample, so a property test example
    does not rebuild the archives.
    """
    archive = synthetic_archive(version)
    return Candidate(version=version, asset=asset_name(version), size=len(archive), sha256=hashlib.sha256(archive).hexdigest(),
                     trust=UPSTREAM_DIGEST if version == PIN else EVIDENCE_ONLY_HTTPS, source=asset_url(version, asset_name(version)),
                     acquired=_ACQUIRED)


def sample_files() -> dict[str, bytes]:
    """The three listed files of a sample bundle: a configuration copy and the real trust records of both candidates."""
    return {CLIFF_TOML: b'[changelog]\nbody = "{{ version }}"\n', trust_name(PIN): trust_record_bytes(sample_candidate(PIN)),
            trust_name(BASELINE): trust_record_bytes(sample_candidate(BASELINE))}


def _identity(version: str) -> CandidateIdentity:
    """The bundle's identity of a candidate: its trust record's, with an executable digest."""
    candidate = sample_candidate(version)
    return CandidateIdentity(version=version, asset=candidate.asset, size=candidate.size, sha256=candidate.sha256, trust=candidate.trust,
                             executable_sha256="e" * 64)


def sample_inputs() -> FrozenInputs:
    """Frozen inputs over the full matrix: llm-shared with one tag, then the fixture with its own tags."""
    files = sample_files()
    return FrozenInputs(
        pin=PIN, baseline=BASELINE, llm_shared_commit=COMMIT, llm_shared_tags=(("v0.1.0", "1" * 40),),
        cliff_toml=CliffToml(source="tools/dev_workflow/cliff.toml", sha256=hashlib.sha256(files[CLIFF_TOML]).hexdigest(),
                             dev_workflow_commit=DEV_WORKFLOW),
        fixture=FixtureHashes(head="a" * 40, tags=tuple((name, f"{index:x}" * 40) for index, name in enumerate(TAGS, start=1))),
        ranges=SAMPLE_RANGES, candidates=(_identity(BASELINE), _identity(PIN)),
    )


def sample_outputs() -> ComparisonResult:
    """Every case is identical but `DIFFERING`, which differs by one hunk."""
    same = RunDigest("1" * 64, 0)
    return ComparisonResult(tuple(
        CaseResult(case, ((BASELINE, RunDigest("2" * 64, 0)), (PIN, RunDigest("3" * 64, 0))), (_HUNK,)) if case == DIFFERING
        else CaseResult(case, ((BASELINE, same), (PIN, same)))
        for case in SAMPLE_RANGES
    ))


def sample_bundle(directory: Path | None = None) -> Bundle:
    """A complete bundle; given a directory, its listed digests are those of the files there."""
    files = sample_files()
    digests = tuple(sorted((name, hashlib.sha256(content).hexdigest()) for name, content in files.items()))
    categories = tuple(AuditCategory(name, (f"git-cliff/src/{index}.rs:1",), f"no path of {name} returns 69")
                       for index, name in enumerate(AUDIT_CATEGORIES, start=1))
    return Bundle(
        inputs=sample_inputs(), outputs=sample_outputs(),
        files=digests if directory is None else file_digests(directory, PIN, BASELINE),
        classification=(Classification(f"{DIFFERING.key} #1", "intentional", "2.14.2: multiple commit parsers can apply (release notes)"),),
        audit=Audit(revision="d" * 40, excludes_69=True, commands=("git clone --depth 1 --branch v2.14.2 <url> <dir>",), categories=categories),
        observed_statuses=(ObservedStatus("success", "git-cliff --version", 0), ObservedStatus("usage error", "git-cliff --bad", 2),
                           ObservedStatus("failing render", "git-cliff -c broken.toml", 1)),
    )


def place_bundle(directory: Path, **changes: object) -> Bundle:
    """Write the listed files and a complete bundle, with optional field changes, into a directory."""
    directory.mkdir(parents=True, exist_ok=True)
    for name, content in sample_files().items():
        (directory / name).write_bytes(content)
    bundle = dataclasses.replace(sample_bundle(directory), **changes)
    write(directory, bundle)
    assert (directory / BUNDLE_FILE).is_file()
    return bundle


