"""The evidence harness fakes: canned release metadata, a recording Git, scripted git-cliff runs and sample bundles.

Step 6 of v0.14.0 git-cliff-provisioning (plan "Shared test architecture",
plan decision Q12). No process, socket, network or real Git:

- `release_metadata` and `metadata`: GitHub release metadata for a synthetic
  candidate archive, with or without its published `sha256:` digest, and the
  metadata worker child that reports it, for the children fake's `metadata`
  role.
- `FakeGit`: the `subprocess.run` replacement behind a real
  `GitExecutionContext`. It answers `git --version`, records every other call
  with its arguments, subcommand, working directory, environment, input bytes
  and standard input setting, and answers each subcommand from a declared
  value or function (empty output by default); since code review round 1 an
  action (`worktree remove`) can be declared to fail with its status and
  standard error. `git_context` builds the
  context over it from any source environment; `tag_listing` and
  `refs_listing` write the outputs of the two `for-each-ref` formats.
- `CliffRuns`: the launch seam of git-cliff runs started through real
  invocation objects: it records each request and answers by version and case
  (`<repository> <range or full history>`), identical outputs by default.
- `sample_bundle`, `sample_files` and `place_bundle`: a complete bundle whose
  listed files exist beside it. Since code review round 1 it holds the full
  matrix (llm-shared's chained ranges of one tag, then the fixture's), one
  case differing by one hunk (`DIFFERING`, at `DIFFERING_INDEX`), real trust
  records of both candidates (`sample_candidate`), an audit covering every
  exit-path category and the three required observed statuses.
"""

